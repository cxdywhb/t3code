export const ISSUE_AUTOMATION_COMMENT_MARKER = "[T3-Auto-Analysis]";

const commentHeading = "## 禅道评论";
const commentSignature = "Generated by ym-dev-zenbug AI Agent Skill";

export const ISSUE_AUTOMATION_COMMENT_INSTRUCTIONS = [
  "在最终报告末尾增加以下小节。由 T3 按规则同步，不要直接发表禅道评论。",
  commentHeading,
  "问题原因：用一句话说明用户在什么情况下遇到什么问题，以及已确认的原因；原因未确认时说明仍在排查。",
  "解决方案：用一句话说明怎么处理及预期表现。尚未实施时用「建议」表述。没有确认的方案时可以省略此行。",
  "小节使用以上标签和纯文本，每项占一行，不用列表或代码块。面向测试和产品同事，省略模型、Skill、代码路径、分支、提交、命令和验证细节。只有实际完成并验证的修复才能写为已修复。",
].join("\n");

export function formatIssueAutomationWriteBackComment(report: string): string {
  const lines = report.split(/\r?\n/).map((line) => line.trim());
  const headingIndex = lines.lastIndexOf(commentHeading);
  const [reasonLine = "", solutionLine = ""] =
    headingIndex === -1 ? [] : lines.slice(headingIndex + 1).filter(Boolean);
  const reason = reasonLine.match(/^问题原因[：:](.+)$/)?.[1]?.trim();
  const solution = solutionLine.match(/^解决方案[：:](.+)$/)?.[1]?.trim();

  return [
    `问题原因：${reason || "本次报告未提供简明原因，请在 T3 Code 查看诊断详情。"}`,
    ...(reason && solution ? [`解决方案：${solution}`] : []),
    "",
    ISSUE_AUTOMATION_COMMENT_MARKER,
    commentSignature,
  ].join("\n");
}
